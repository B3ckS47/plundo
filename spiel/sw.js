async function load(f) {
  const r = await fetch(new Request(f + (f.includes('?') ? '&' : '?') + 'v=' + ALL[f], {cache: 'reload'}));
  if (!r.ok) throw new Error('Laden fehlgeschlagen: ' + f);
  const hd = new Headers(r.headers); hd.set('x-v', ALL[f]);
  return new Response(await r.blob(), {status: r.status, statusText: r.statusText, headers: hd});
}
